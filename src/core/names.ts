/** Deterministic pool of clearly-fictional (but natural looking) Korean names. */
export function fakeName(index: number): string {
  const s = FAKE_SURNAMES[index % FAKE_SURNAMES.length]
  const g = FAKE_GIVEN[(index * 7 + Math.floor(index / FAKE_SURNAMES.length)) % FAKE_GIVEN.length]
  return s + g
}
