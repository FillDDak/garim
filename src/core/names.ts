const LABEL_WORDS = new Set(NAME_LABELS.map((l) => l.replace(/\\s\?/g, '')))

export function startsWithSurname(word: string): boolean {
  if (COMPOUND_SURNAMES.some((s) => word.startsWith(s) && word.length >= 3)) return true
  return SINGLE_SURNAMES.has(word[0])
}

/** Heuristic: is `word` a plausible Korean full name (surname + given name)? */
export function isPlausibleName(word: string, minLen = 3): boolean {
  if (!/^[가-힣]+$/.test(word)) return false
  if (word.length < minLen || word.length > 4) return false
  if (NAME_STOPWORDS.has(word) || LABEL_WORDS.has(word)) return false
  if (word.length === 4) return COMPOUND_SURNAMES.some((s) => word.startsWith(s))
  return startsWithSurname(word)
}

